-- Consent-based storefront analytics hardening.
-- Existing analytics_sessions / analytics_events rows are preserved; all changes are additive.

CREATE TABLE IF NOT EXISTS public.analytics_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  visitor_hash text NOT NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  landing_path text NOT NULL DEFAULT '/',
  current_path text,
  exit_path text,
  referrer text,
  country_code text,
  region text,
  city text,
  device_type text,
  browser text,
  operating_system text,
  language text,
  timezone text,
  screen_width integer,
  screen_height integer,
  viewport_width integer,
  viewport_height integer,
  consent_version integer,
  consent_granted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.analytics_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id uuid NOT NULL REFERENCES public.analytics_sessions(id) ON DELETE CASCADE,
  event_name text NOT NULL,
  page_path text NOT NULL,
  page_title text,
  referrer text,
  duration_ms integer,
  event_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.analytics_sessions
  ADD COLUMN IF NOT EXISTS consent_granted_at timestamptz;
ALTER TABLE public.analytics_events
  ADD COLUMN IF NOT EXISTS event_data jsonb NOT NULL DEFAULT '{}'::jsonb;

CREATE INDEX IF NOT EXISTS analytics_sessions_last_seen_idx
  ON public.analytics_sessions (last_seen_at DESC);
CREATE INDEX IF NOT EXISTS analytics_sessions_started_at_idx
  ON public.analytics_sessions (started_at DESC);
CREATE INDEX IF NOT EXISTS analytics_events_created_at_idx
  ON public.analytics_events (created_at DESC);
CREATE INDEX IF NOT EXISTS analytics_events_session_created_idx
  ON public.analytics_events (session_id, created_at ASC);
CREATE INDEX IF NOT EXISTS analytics_events_page_created_idx
  ON public.analytics_events (page_path, created_at DESC);

ALTER TABLE public.analytics_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analytics_sessions FORCE ROW LEVEL SECURITY;
ALTER TABLE public.analytics_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analytics_events FORCE ROW LEVEL SECURITY;

-- Browser clients never access analytics tables directly. The API uses the server-only
-- service_role key to accept consented events; admin reads pass through requireAdmin.
REVOKE ALL PRIVILEGES ON TABLE public.analytics_sessions FROM anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.analytics_events FROM anon, authenticated;
GRANT ALL PRIVILEGES ON TABLE public.analytics_sessions TO service_role;
GRANT ALL PRIVILEGES ON TABLE public.analytics_events TO service_role;

DO $$
DECLARE
  event_sequence text;
BEGIN
  event_sequence := pg_get_serial_sequence('public.analytics_events', 'id');
  IF event_sequence IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO service_role', event_sequence);
  END IF;
END $$;
